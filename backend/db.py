"""Database backend seam (roadmap Phase 2 - PostgreSQL migration, M2).

``backend/store.py`` speaks raw SQL against a DB-API connection. Historically that
connection was always SQLite. This module introduces a thin seam so the *same*
store.py code can run on either:

  * **SQLite** - the default, unchanged. This is the shipping behaviour; nothing
    about it changes unless an operator opts in.
  * **PostgreSQL** - opt-in via ``DSPM_DB_URL`` (a libpq DSN/URL). This is the
    security milestone: the credential store (users.password_hash,
    api_keys.key_hash, encrypted vault ``secrets``) moves off-host onto a
    least-privilege, TLS-fronted, encrypted-at-rest server instead of a flat file.

Design principle: **keep the SQLite path byte-for-byte identical**. In SQLite
mode we yield the raw ``sqlite3.Connection`` (with ``row_factory = Row`` and
``PRAGMA foreign_keys = ON``), so the default deployment behaves exactly as
before. *All* Postgres-specific behaviour lives behind ``_PgConn``, which
translates the small, closed set of SQLite-isms store.py actually uses into their
PostgreSQL equivalents:

  * ``?`` positional placeholders   -> ``%s``               (psycopg client binding)
  * ``INSERT OR REPLACE``           -> ``INSERT ... ON CONFLICT (pk) DO UPDATE``
  * ``INSERT OR IGNORE``            -> ``INSERT ... ON CONFLICT DO NOTHING``
  * ``PRAGMA foreign_keys``         -> no-op (FKs are always enforced in Postgres)
  * ``PRAGMA table_info(t)``        -> ``information_schema.columns`` (via table_columns)
  * ``executescript(ddl)``          -> split + per-statement execute, with the DDL
                                       type/identity constructs translated
  * ``INTEGER PRIMARY KEY AUTOINCREMENT`` -> ``BIGINT GENERATED BY DEFAULT AS IDENTITY``
  * ``... REAL`` (epoch column)     -> ``DOUBLE PRECISION`` (float4 loses epoch precision)

and a row object (:class:`_PgRow`) that supports both ``row["col"]`` and
``row[0]`` just like ``sqlite3.Row``.

The translation functions (:func:`translate_sql`, :func:`translate_schema`,
:func:`split_statements`) are pure and are unit-tested offline in
``tests/test_db_dialect.py`` - no server required. The full round-trip against a
real PostgreSQL is exercised by ``tests/test_postgres_backend.py``, which is
skipped unless ``DSPM_DB_URL`` points at a reachable Postgres (see the operator
runbook in the Phase 2 roadmap).
"""

from __future__ import annotations

import os
import re
import sqlite3
from contextlib import contextmanager
from pathlib import Path
from typing import Any, Iterable, Iterator, Sequence

try:  # psycopg is an OPTIONAL dependency - only needed when DSPM_DB_URL is a Postgres DSN.
    import psycopg  # type: ignore
except Exception:  # pragma: no cover - import guard; absence is the SQLite-only norm
    psycopg = None  # type: ignore


# ---------------------------------------------------------------------------
# Backend selection
# ---------------------------------------------------------------------------

_PG_URL_PREFIXES = ("postgres://", "postgresql://")


def db_url() -> str:
    return os.getenv("DSPM_DB_URL", "").strip()


def is_postgres() -> bool:
    """True iff DSPM_DB_URL selects a PostgreSQL backend. Read live so tests can
    monkeypatch the environment."""
    return db_url().lower().startswith(_PG_URL_PREFIXES)


def is_sqlite() -> bool:
    return not is_postgres()


def backend_name() -> str:
    return "postgres" if is_postgres() else "sqlite"


# ``store.py`` catches this around a best-effort retry. A tuple works in ``except``
# and covers whichever backend is active (psycopg only when it is installed).
if psycopg is not None:
    OperationalError: tuple = (sqlite3.OperationalError, psycopg.OperationalError)
else:  # pragma: no cover - trivial
    OperationalError = (sqlite3.OperationalError,)


# ---------------------------------------------------------------------------
# Primary keys - needed to rewrite ``INSERT OR REPLACE`` into ``ON CONFLICT``.
# Kept in sync with the schema in ``store.init_db`` (guarded by a test).
# ---------------------------------------------------------------------------

_PK: dict[str, tuple[str, ...]] = {
    "scan_reports": ("tenant_id", "scan_id"),
    "scan_runs": ("tenant_id", "id"),
    "assets": ("tenant_id", "id"),
    "asset_versions": ("tenant_id", "asset_id", "version"),
    "findings": ("tenant_id", "id"),
    "scan_jobs": ("id",),
    "secrets": ("tenant_id", "secret_id"),
    "revoked_tokens": ("jti",),
    "tenants": ("tenant_id",),
}


# ---------------------------------------------------------------------------
# Pure SQL-dialect translation (unit-tested offline)
# ---------------------------------------------------------------------------

_INSERT_REPLACE_RE = re.compile(r"^\s*INSERT\s+OR\s+REPLACE\s+INTO\s+(\w+)\s*\(([^)]*)\)", re.IGNORECASE)
_INSERT_IGNORE_RE = re.compile(r"^\s*INSERT\s+OR\s+IGNORE\s+INTO\s+(\w+)", re.IGNORECASE)


def _rewrite_upsert(sql: str) -> str:
    """Rewrite SQLite ``INSERT OR REPLACE`` / ``INSERT OR IGNORE`` into the
    Postgres ``ON CONFLICT`` forms. Operates on the ``?``-placeholder form (run
    this BEFORE placeholder translation)."""
    m = _INSERT_REPLACE_RE.match(sql)
    if m:
        table = m.group(1).lower()
        cols = [c.strip() for c in m.group(2).split(",") if c.strip()]
        pk = _PK.get(table)
        if not pk:
            raise ValueError(f"db: no primary-key mapping for INSERT OR REPLACE INTO {table}")
        head = "INSERT INTO " + m.group(1) + " (" + ", ".join(cols) + ")"
        body = (sql[: m.start()] + head + sql[m.end():]).rstrip().rstrip(";")
        conflict = "(" + ", ".join(pk) + ")"
        set_cols = [c for c in cols if c not in pk]
        if set_cols:
            set_clause = ", ".join(f"{c} = EXCLUDED.{c}" for c in set_cols)
            return f"{body} ON CONFLICT {conflict} DO UPDATE SET {set_clause}"
        # All columns are part of the PK: replacing changes nothing -> DO NOTHING.
        return f"{body} ON CONFLICT {conflict} DO NOTHING"
    m = _INSERT_IGNORE_RE.match(sql)
    if m:
        body = (sql[: m.start()] + "INSERT INTO " + m.group(1) + sql[m.end():]).rstrip().rstrip(";")
        return f"{body} ON CONFLICT DO NOTHING"
    return sql


def _translate_placeholders(sql: str) -> str:
    """``?`` -> ``%s`` (outside single-quoted string literals) and double any
    literal ``%`` so psycopg's client-side binding leaves it intact. store.py's
    SQL contains no ``?`` inside literals and no literal ``%``; the scan is a
    defensive correctness guarantee, not a workaround for anything present today."""
    out: list[str] = []
    in_str = False
    for ch in sql:
        if ch == "'":
            in_str = not in_str
            out.append(ch)
        elif ch == "%":
            out.append("%%")
        elif ch == "?" and not in_str:
            out.append("%s")
        else:
            out.append(ch)
    return "".join(out)


def translate_sql(sql: str) -> str:
    """Translate one SQLite statement into its PostgreSQL equivalent."""
    return _translate_placeholders(_rewrite_upsert(sql))


def translate_schema(ddl: str) -> str:
    """Translate the SQLite DDL constructs used by ``store.init_db`` into Postgres.

    Only two type/identity constructs are non-portable; everything else
    (``TEXT``/``INTEGER``, ``PRIMARY KEY``, ``CHECK``, ``CREATE INDEX IF NOT
    EXISTS``, ``ALTER TABLE ADD COLUMN``) is already valid PostgreSQL."""
    out = re.sub(
        r"INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT",
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        ddl,
        flags=re.IGNORECASE,
    )
    # The only REAL column is login_failures.timestamp, which stores a Unix epoch
    # (time.time()). Postgres REAL is float4 (~7 significant digits) and cannot
    # represent a ~10-digit epoch second, let alone sub-second - use float8.
    out = re.sub(r"\bREAL\b", "DOUBLE PRECISION", out, flags=re.IGNORECASE)
    return out


def split_statements(script: str) -> list[str]:
    """Split a multi-statement DDL script on ``;`` (ignoring ``;`` inside single
    quotes) after stripping ``--`` line comments, for backends without an
    ``executescript`` shortcut."""
    lines = []
    for line in script.splitlines():
        idx = line.find("--")
        if idx != -1:
            line = line[:idx]
        lines.append(line)
    cleaned = "\n".join(lines)

    stmts: list[str] = []
    buf: list[str] = []
    in_str = False
    for ch in cleaned:
        if ch == "'":
            in_str = not in_str
            buf.append(ch)
        elif ch == ";" and not in_str:
            stmt = "".join(buf).strip()
            if stmt:
                stmts.append(stmt)
            buf = []
        else:
            buf.append(ch)
    tail = "".join(buf).strip()
    if tail:
        stmts.append(tail)
    return stmts


# ---------------------------------------------------------------------------
# Row object - dual int/str indexing, like sqlite3.Row
# ---------------------------------------------------------------------------

class _PgRow:
    """A result row that supports both ``row["col"]`` and ``row[0]``, plus the
    small mapping surface (``keys``/``get``/``len``/iter/``dict(row)``) that
    store.py relies on from ``sqlite3.Row``."""

    __slots__ = ("_index", "_values")

    def __init__(self, index: dict[str, int], values: Sequence[Any]) -> None:
        self._index = index
        self._values = tuple(values)

    def __getitem__(self, key: Any) -> Any:
        if isinstance(key, (int, slice)):
            return self._values[key]
        return self._values[self._index[key]]

    def __len__(self) -> int:
        return len(self._values)

    def __iter__(self) -> Iterator[Any]:
        return iter(self._values)

    def keys(self) -> list[str]:
        return list(self._index)

    def get(self, key: str, default: Any = None) -> Any:
        i = self._index.get(key)
        return default if i is None else self._values[i]

    def __repr__(self) -> str:  # pragma: no cover - debug aid
        return f"_PgRow({dict(zip(self._index, self._values))!r})"


def _pg_row_factory(cursor: Any):
    desc = cursor.description
    cols = [d.name for d in desc] if desc else []
    index = {name: i for i, name in enumerate(cols)}

    def make_row(values: Sequence[Any]) -> _PgRow:
        return _PgRow(index, values)

    return make_row


# ---------------------------------------------------------------------------
# Postgres connection wrapper - mimics the sqlite3.Connection subset store.py uses
# ---------------------------------------------------------------------------

class _PgConn:
    def __init__(self, raw: Any) -> None:
        self._raw = raw

    def execute(self, sql: str, params: Iterable[Any] = ()):  # noqa: D401
        # Always pass a sequence (never None) so psycopg runs client-side binding
        # and un-doubles any ``%%`` we introduced.
        return self._raw.execute(translate_sql(sql), tuple(params))

    def executescript(self, script: str) -> None:
        for stmt in split_statements(translate_schema(script)):
            self._raw.execute(stmt)

    def commit(self) -> None:
        self._raw.commit()

    def rollback(self) -> None:
        self._raw.rollback()

    def close(self) -> None:
        self._raw.close()


def _pg_connect() -> _PgConn:
    if psycopg is None:  # pragma: no cover - exercised only in a misconfigured env
        raise RuntimeError(
            "DSPM_DB_URL selects PostgreSQL but psycopg is not installed. "
            "Install it with:  pip install \"psycopg[binary]\""
        )
    timeout = int(os.getenv("DSPM_DB_CONNECT_TIMEOUT", "10"))
    raw = psycopg.connect(
        db_url(),
        autocommit=False,
        row_factory=_pg_row_factory,
        connect_timeout=timeout,
    )
    return _PgConn(raw)


# ---------------------------------------------------------------------------
# Public connect() - the seam store._connect() delegates to
# ---------------------------------------------------------------------------

@contextmanager
def connect(sqlite_path: Path):
    """Yield a connection for the active backend, commit on clean exit, always close.

    SQLite: the raw ``sqlite3.Connection`` (row_factory + FK pragma), i.e. the
    exact object and setup store.py has always used. Postgres: a :class:`_PgConn`
    wrapper providing the same execute/executescript/commit surface."""
    if is_postgres():
        conn = _pg_connect()
        try:
            yield conn
            conn.commit()
        finally:
            conn.close()
    else:
        Path(sqlite_path).parent.mkdir(parents=True, exist_ok=True)
        conn = sqlite3.connect(sqlite_path)
        try:
            conn.row_factory = sqlite3.Row
            conn.execute("PRAGMA foreign_keys = ON")
            yield conn
            conn.commit()
        finally:
            conn.close()


def table_columns(conn: Any, table: str) -> set[str]:
    """Column names of ``table`` - the backend-appropriate replacement for
    ``PRAGMA table_info(table)`` (used by store.init_db for ALTER migrations)."""
    if is_postgres():
        rows = conn.execute(
            "SELECT column_name FROM information_schema.columns "
            "WHERE table_name = ? AND table_schema = current_schema()",
            (table,),
        ).fetchall()
        return {r[0] for r in rows}
    rows = conn.execute(f"PRAGMA table_info({table})").fetchall()
    return {r["name"] for r in rows}
